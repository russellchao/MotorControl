/* USER CODE BEGIN 4 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if (htim->Instance == TIM6) {
	// Interrupt to check the encoder pulses from this sample and calculate the ensuing on_period for TIM3
	// NOTE: (tim3_on_period / htim3.Init.Period) * 100 = Duty Cycle for TIM3

	// Set pin PA4 HIGH at the start of the ISR
	HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);

	// Take the number of pulses (ticks from TIM2) from this sample and reset TIM2
	pulses_this_sample = __HAL_TIM_GET_COUNTER(&htim2);
	TIM2->CNT = 0;

	// Feedforward PID Control
	static float integral = 0.0f;
	const float min_on_period = htim3.Init.Period * 0.05f;
	const float max_on_period = htim3.Init.Period * 0.95f;

	float error = (float)target_pulses_per_sample - (float)pulses_this_sample;
	integral += error;

	float on_period = FF_OFFSET + (FF_SLOPE * target_pulses_per_sample) + (KP * error) + (KI * integral);

	// Clamp PWM between 5-95%
	if (on_period > max_on_period)
	{
		on_period = max_on_period;
		integral -= error;
	}
	if (on_period < min_on_period)
	{
		on_period = min_on_period;
		integral -= error;
	}

	tim3_on_period = (uint32_t)on_period;

	// Set the new on_period to TIM3
	__HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, tim3_on_period);

	new_sample = 1;

	// Set pin PA4 LOW at the end of the ISR
	HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);

	// Kick off one ADC conversion; HAL_ADC_ConvCpltCallback fires when it's done
	HAL_ADC_Start_IT(&hadc1);
  }
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc) {
	// Runs in interrupt context: grab the result and get out
	if (hadc->Instance == ADC1)
	{
		adc_raw = (uint32_t)HAL_ADC_GetValue(hadc);  // already 0..1023 (10-bit)
		//target_pulses_per_sample = adc_raw;
		adc_ready = 1;
	}
}

void print_adc() {
	// raw 0..1023 maps linearly onto 0 .. 3.3 V (VDDA on the Nucleo)
	char textbuffer[64];
	uint32_t raw = adc_raw;                 // copy once so ISR can't change it mid-calc
	uint32_t mv  = (raw * 3300u) / 1023u;   // integer millivolts
	int len = snprintf(
		textbuffer, sizeof(textbuffer), "ADC: %4lu / 1023 | %lu.%03lu V\r\n", raw, mv / 1000, mv % 1000
	);
	HAL_UART_Transmit(&huart2, (uint8_t *)textbuffer, len, 100);
}

void print_pulses_and_dc() {
	// Output the No. Pulses from the last ISR Sample and new TIM3 Duty Cycle to CoolTerm
	char textbuffer[64];
	uint32_t duty_cycle = (tim3_on_period * 100) / (htim3.Init.Period + 1);
	int len = snprintf(
		textbuffer, sizeof(textbuffer), "Pulses This Sample: %lu | TIM3 Duty Cycle: %lu%%\r\n", pulses_this_sample, duty_cycle
	);
	HAL_UART_Transmit(&huart2, (uint8_t *)textbuffer, len, 100);
}
